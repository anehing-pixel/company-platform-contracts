package com.company.platform.event;

/**
 * 事件消费方契约（机制层）。
 *
 * <p><b>实现方是谁</b>：每个服务在自己的包里实现本接口，由事件调度器定时驱动；
 * 服务没有实现类时调度器直接跳过。</p>
 *
 * <p><b>三条必须守住的约定</b>（违反即"写了代码没接通"）：</p>
 * <ol>
 *   <li><b>必须幂等</b>。调度器用消费记录表挡重复投递，但"消费成功、写游标前进程被杀"
 *       的窗口仍会重放。{@link #consume} 自己必须能扛重复调用。</li>
 *   <li><b>不许吞异常</b>。抛异常＝消费失败，调度器记 attempts 且游标不前进；
 *       catch 住返回正常会把坏数据标成 DONE 永久丢失。</li>
 *   <li><b>不许做服务间同步调用</b>。消费跑在调度线程里，没有请求上下文与调用方 JWT；
 *       需要跨服务取数请在本服务表里落一份，或显式设计带凭证的通路。</li>
 * </ol>
 */
public interface EventConsumer {

    /**
     * 消费方标识，写进消费游标与消费记录表，也是幂等键的一半。
     * 约定用服务名，不要用类名——一个服务多个消费者共用服务名会让游标互相覆盖。
     */
    String name();

    /**
     * 订阅的事件类型集合。调度器据此过滤拉取；返回空集合＝不订阅任何事件。
     */
    java.util.Set<String> eventTypes();

    /**
     * 处理一条事件。正常返回＝消费成功（置 DONE 并推进游标）；
     * 抛任何异常＝消费失败（记 attempts/last_error，下轮重试，超限置 DEAD）。
     */
    void consume(DomainEvent event);
}
